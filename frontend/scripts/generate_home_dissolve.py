"""Regenerate Home's alpha matte; only Python's standard library is needed."""

import math
import random
from collections import defaultdict
from pathlib import Path


def smooth(value: float) -> float:
    value = max(0.0, min(1.0, value))
    return value * value * (3 - 2 * value)


def density(x: float, y: float) -> float:
    # Unequal elliptical corners, gently perturbed; the entire top stays full.
    inward = 48 * smooth((y - 80) / 240)
    left_span, right_span = 610 + inward, 570 + inward
    left = math.hypot((x - left_span) / left_span, (y - 48) / 272) if x < left_span else 0
    right_start = 1600 - right_span
    right = math.hypot((x - right_start) / right_span, (y - 56) / 264) if x > right_start else 0
    wobble = 0.025 * math.sin(y * 0.055 + x * 0.012)
    wobble += 0.015 * math.sin(y * 0.13 - x * 0.021)
    erosion = smooth((max(left, right) + wobble - 0.72) / 0.66)
    return 1 - erosion * smooth((y - 40) / 72)


def stream_texture(rng: random.Random, coverage: float) -> str:
    """One seamless repeat of stepped filaments, clusters and detached pixels."""
    paths = []
    y = 0.0
    while y < 320:
        pitch = rng.choice([1, 1, 1.5, 1.5, 2, 2, 2.5, 3, 4])
        x = 0
        while x < 256:
            width = min(256 - x, rng.choice([2, 4, 8, 14, 14, 24, 38, 62, 92, 128]))
            # Correlated patches interrupt the grain: isolated pixels coexist
            # with thicker clusters instead of one evenly spaced scanline grid.
            patch = math.sin(x * 0.045 + y * 0.08) + math.sin(x * 0.019 - y * 0.13)
            chance = coverage + patch * coverage * (1 - coverage) * 0.3
            if rng.random() < chance:
                gap = (1 - coverage) * rng.uniform(0.05, pitch * 0.24)
                step = min(pitch * 0.2, (1 - coverage) * rng.choice([0.5, 1, 1.5]))
                shoulder = x + width * rng.uniform(0.15, 0.45)
                tail = x + width * rng.uniform(0.55, 0.9)
                paths.append(
                    f"M{x} {y + gap + step:.2f}H{shoulder:.1f}V{y + gap:.2f}"
                    f"H{tail:.1f}V{y + gap + step:.2f}H{x + width}"
                    f"V{y + pitch - gap:.2f}H{tail:.1f}V{y + pitch - gap - step:.2f}"
                    f"H{shoulder:.1f}V{y + pitch - gap:.2f}H{x}Z"
                )
            x += width
        y += pitch
    return "".join(paths)


def build_mask() -> str:
    rng = random.Random(72419)
    bands: dict[tuple[int, str], list[str]] = defaultdict(list)
    # Stationary coverage contours keep the approved silhouette in place. The
    # texture flows through them, rather than rocking the entire edge sideways.
    for y in range(0, 320, 2):
        start = 0
        previous = (-2, "")
        for x in range(0, 1604, 4):
            value = density(x + 2, y + 1) if x < 1600 else -1
            level = -1 if value >= 0.995 else min(11, int(value * 12))
            band = (level, "core" if level == -1 else "left" if x < 800 else "right")
            if band != previous:
                if previous != (-2, ""):
                    bands[previous].append(f"M{start} {y}h{x - start}v2H{start}Z")
                start, previous = x, band

    definitions = []
    body = '<path d="' + "".join(bands[-1, "core"]) + '"/>'
    for index in range(12):
        definitions.append(
            f'<pattern id="grain{index}" width="256" height="320" '
            'patternUnits="userSpaceOnUse"><path fill="white" '
            f'd="{stream_texture(rng, (index + 0.5) / 12)}"/></pattern>'
        )
        for side in ["left", "right"]:
            definitions.append(
                f'<clipPath id="band{index}-{side}">'
                f'<path d="{"".join(bands[index, side])}"/></clipPath>'
            )
            body += (
                f'<g clip-path="url(#band{index}-{side})"><g class="stream {side}" '
                f'style="animation-duration:{12.8 + (index * 7 % 13) * 0.64:.2f}s;'
                f'animation-delay:{-index * 1.43:.2f}s">'
                f'<path fill="url(#grain{index})" d="M-256 0h2112v320H-256Z"/></g></g>'
            )
    return (
        '<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 1600 320" '
        'preserveAspectRatio="none"><title>Flowing rounded dissolve of opaque '
        "ribbons</title><!-- Generated by scripts/generate_home_dissolve.py. "
        "Seed 72419; each texture translates by exactly one repeat for a seamless loop. -->"
        "<style>@keyframes flow {to {transform:translateX(-256px)}}"
        "@keyframes flow-right {to {transform:translateX(256px)}}"
        ".stream {animation:flow 18s linear(0,.12 15%,.36 34%,.65 62%,.9 88%,1) infinite}"
        ".right {animation-name:flow-right}"
        "#still:target ~ g .stream {animation:none}</style>"
        '<view id="still" viewBox="0 0 1600 320"/>'
        f'<defs>{"".join(definitions)}</defs><g fill="white">{body}</g></svg>\n'
    )


if __name__ == "__main__":
    target = Path(__file__).resolve().parents[1] / "public/illustrations/home-dissolve.svg"
    target.write_text(build_mask())
